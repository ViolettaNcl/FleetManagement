import { chromium, request } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { randomBytes } from "node:crypto";

const base="http://127.0.0.1:5095";
const adminEmail=process.env.Fleet__BootstrapAdminEmail;
const adminPassword=process.env.Fleet__BootstrapAdminPassword;
const viewerEmail="connected-viewer@example.test";
const viewerPassword="Viewer!aA"+randomBytes(24).toString("hex");
const api=await request.newContext({baseURL:base});
const login=await api.post("/api/auth/login",{data:{email:adminEmail,password:adminPassword}});
assert.equal(login.status(),200);
const adminToken=(await login.json()).accessToken;
const create=await api.post("/api/admin/users",{data:{email:viewerEmail,password:viewerPassword,role:"Viewer"},headers:{Authorization:"Bearer "+adminToken}});
assert.equal(create.status(),201);
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1366,height:900}});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
try{
    await mkdir("browser-results",{recursive:true});
    await page.goto(base+"/console");
    await page.getByRole("heading",{name:"Sign in to the fleet server"}).waitFor();
    await page.getByLabel("Email").fill(adminEmail);
    await page.getByLabel("Password").fill("invalid-password");
    await page.getByRole("button",{name:"Sign in",exact:true}).click();
    await page.getByRole("status").filter({hasText:"Authentication failed"}).waitFor();
    assert.equal(await page.getByLabel("Password").inputValue(),"");
    await page.getByLabel("Password").fill(adminPassword);
    await page.getByRole("button",{name:"Sign in",exact:true}).click();
    await page.getByRole("heading",{name:"Operations overview"}).waitFor();
    await page.locator("#vehicles-count").getByText("4",{exact:true}).waitFor();
    await page.getByRole("button",{name:"Maintenance",exact:true}).click();
    await page.locator("#work-form").getByLabel("Vehicle").selectOption("3");
    await page.locator("#work-form").getByLabel("Category").selectOption("Repair");
    await page.locator("#work-form").getByLabel("Cost (EUR, optional)").fill("12.50");
    const literal="<b>QA literal note</b>";
    await page.locator("#work-form").getByLabel("Notes").fill(literal);
    await page.getByLabel("Confirm this completed work").check();
    await page.getByRole("button",{name:"Save work record"}).click();
    await page.getByRole("status").filter({hasText:"Record saved and server data refreshed"}).waitFor();
    const row=page.locator("#work").getByRole("row").filter({hasText:literal});
    await row.waitFor();assert.equal(await row.locator("b").count(),0);
    await page.getByRole("button",{name:"Resources",exact:true}).click();
    const start=new Date(Date.now()+3*86400000).toISOString().slice(0,16);
    const end=new Date(Date.now()+3*86400000+3600000).toISOString().slice(0,16);
    const shift=page.locator("#shift-form");
    await shift.getByLabel("Driver").selectOption("3");
    await shift.getByLabel("Start (UTC)").fill(start);
    await shift.getByLabel("End (UTC)").fill(end);
    await shift.getByLabel("Confirm shift in UTC").check();
    await shift.getByRole("button",{name:"Save shift"}).click();
    await page.getByRole("status").filter({hasText:"Record saved and server data refreshed"}).waitFor();
    const reserve=page.locator("#reservation-form");
    await reserve.getByLabel("Vehicle").selectOption("3");
    await reserve.getByLabel("Start (UTC)").fill(start);
    await reserve.getByLabel("End (UTC)").fill(end);
    await reserve.getByLabel("Notes").fill("QA console reservation");
    await reserve.getByLabel("Confirm reservation in UTC").check();
    await reserve.getByRole("button",{name:"Reserve vehicle"}).click();
    await page.getByRole("status").filter({hasText:"Record saved and server data refreshed"}).waitFor();
    await page.locator("#reservations").getByRole("row").filter({hasText:"QA console reservation"}).waitFor();
    await page.getByRole("button",{name:"Audit",exact:true}).click();
    await page.locator("#audit").getByText("MaintenanceEntry",{exact:true}).first().waitFor();
    assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
    await page.getByRole("button",{name:"Fleet register",exact:true}).click();
    await page.screenshot({path:"browser-results/connected-admin.png",fullPage:true});
    await page.getByRole("button",{name:"Sign out",exact:true}).click();
    assert.equal(await page.locator("#vehicles tbody tr").count(),0);
    await page.getByLabel("Email").fill(viewerEmail);
    await page.getByLabel("Password").fill(viewerPassword);
    await page.getByRole("button",{name:"Sign in",exact:true}).click();
    await page.getByRole("heading",{name:"Operations overview"}).waitFor();
    await page.getByRole("button",{name:"Maintenance",exact:true}).click();
    assert.equal(await page.locator("#work-form").isVisible(),false);
    assert.equal(await page.locator("#audit-tab").isVisible(),false);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:"browser-results/connected-viewer-mobile.png",fullPage:true});
    await page.reload();
    await page.getByRole("heading",{name:"Sign in to the fleet server"}).waitFor();
    assert.equal(await page.locator("#workspace").isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log("PASS: connected console login/retry, admin forms, safe text, viewer access, mobile layout and memory-only session");
}finally{
    await browser.close();
    await api.dispose();
}
