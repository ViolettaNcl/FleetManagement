import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:8080/FleetManagement/');
  await page.getByRole('button',{name:'Vehicles',exact:true}).waitFor({timeout:90000});
  await mkdir('browser-results',{recursive:true});
  await page.screenshot({path:'browser-results/overview.png',fullPage:true});
  await page.getByRole('button',{name:'Vehicles',exact:true}).click();
  await page.getByRole('button',{name:'+ Add vehicle',exact:true}).click();
  await page.getByLabel('Registration',{exact:true}).fill('QA-501');
  await page.getByLabel('Model',{exact:true}).fill('QA vehicle');
  await page.getByRole('button',{name:'Save record'}).click();
  await page.getByText('Record saved.',{exact:true}).waitFor();
  await page.getByLabel('Search',{exact:true}).fill('QA-501');
  assert.equal(await page.getByRole('row').filter({hasText:'QA-501'}).count(),1);
  await page.reload();
  await page.getByRole('button',{name:'Vehicles',exact:true}).click();
  await page.getByLabel('Search',{exact:true}).fill('QA-501');
  await page.getByRole('row').filter({hasText:'QA-501'}).waitFor();
  await page.getByLabel('Search',{exact:true}).fill('');
  await page.screenshot({path:'browser-results/vehicles.png',fullPage:true});
  await page.getByRole('button',{name:'Dispatch',exact:true}).click();
  await page.getByRole('button',{name:'Suggest assignment'}).click();
  await page.getByRole('status').filter({hasText:'Suggested'}).waitFor();
  await page.getByRole('button',{name:'Create trip',exact:true}).click();
  await page.getByRole('status').filter({hasText:'saved'}).waitFor();
  await page.screenshot({path:'browser-results/dispatch.png',fullPage:true});
  await page.getByRole('button',{name:'Tracking',exact:true}).click();
  await page.getByRole('button',{name:'+ 15 minutes',exact:true}).click();
  await page.screenshot({path:'browser-results/tracking.png',fullPage:true});
  await page.getByRole('button',{name:'Maintenance',exact:true}).click();
  await page.getByRole('row').filter({hasText:'FM-310'}).getByRole('button',{name:'Record service'}).click();
  await page.getByRole('row').filter({hasText:'FM-310'}).getByText('Healthy',{exact:true}).waitFor();
  await page.screenshot({path:'browser-results/maintenance.png',fullPage:true});
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await page.getByRole('heading',{name:'Vehicle performance'}).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export Excel (.xlsx)'}).click();
  const download=await downloadPromise;
  assert.match(download.suggestedFilename(),/^fleet-report-.*\.xlsx$/);
  await download.saveAs('browser-results/fleet-report.xlsx');
  await page.screenshot({path:'browser-results/analytics.png',fullPage:true});
  await page.getByRole('button',{name:'Calendar',exact:true}).click();
  await page.getByRole('heading',{name:'Fleet calendar'}).waitFor();
  await page.getByRole('button',{name:'Month',exact:true}).click();
  assert.equal(await page.locator('.calendar-day').count(),42);
  await page.getByRole('button',{name:'Week',exact:true}).click();
  assert.equal(await page.locator('.calendar-day').count(),7);
  await page.screenshot({path:'browser-results/calendar.png',fullPage:true});
  await page.getByRole('button',{name:'+ Plan trip',exact:true}).click();
  await page.getByRole('heading',{name:'Intelligent dispatch planner'}).waitFor();
  await page.getByRole('button',{name:'Optimization',exact:true}).click();
  await page.getByRole('heading',{name:'Route optimization lab'}).waitFor();
  await page.getByLabel('Delivery stops').fill('16');
  await page.getByRole('button',{name:'Calculate routes'}).click();
  await page.getByRole('button',{name:'Nearest neighbor',exact:true}).click();
  await page.getByRole('button',{name:'2-opt',exact:true}).click();
  await page.screenshot({path:'browser-results/optimization.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await page.screenshot({path:'browser-results/mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log('Browser smoke checks passed');
} finally { await browser.close(); }
