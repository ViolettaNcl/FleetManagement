import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),axePath=require.resolve('axe-core/axe.min.js');
const browser=await chromium.launch();
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8080/FleetManagement/');
 await page.getByRole('heading',{name:'Operations overview',exact:true}).waitFor({timeout:90000});
 const nav=page.locator('#workspace-nav'),departure=page.locator('.departure-focus');
 const go=async name=>{await page.setViewportSize({width:1440,height:900});await nav.getByRole('button',{name,exact:true}).click();};
 const audit=async label=>{const result=await page.evaluate(async()=>{const r=await axe.run({runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}));});assert.deepEqual(result,[],label);};
 const fit=async root=>{for(const width of [320,390,768,1024,1440]){await page.setViewportSize({width,height:900});await root.waitFor();assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Atlas overflow '+width);}};
 await mkdir('browser-results',{recursive:true});await page.addScriptTag({path:axePath});
 await departure.getByText('#103',{exact:true}).waitFor();
 assert.equal(await departure.locator('.departure-node strong').allTextContents().then(x=>x.join('|')),'Central hub|South depot');
 assert.ok(await departure.getByTestId('departure-time').isVisible());
 await audit('Atlas dark overview');await fit(departure);
 await page.screenshot({path:'browser-results/v6-atlas-overview.png',fullPage:true});
 await departure.getByRole('button',{name:'Review next departure',exact:true}).click();
 await page.getByText('Editing trip #103',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('Origin',{exact:true}).inputValue(),'Central hub');
 await go('Overview');
 // The accessible name must include every visible value in reading order.
 for(const [status,count,share] of [['In transit',2,'50%'],['Scheduled',1,'25%'],['Completed',1,'25%']]){
   const legend=page.getByRole('button',{name:status+' '+count+' '+share+' — Show trips',exact:true});
   await legend.waitFor();
   assert.equal(await legend.locator('strong').innerText(),String(count));
   assert.equal(await legend.locator('small').innerText(),share);
 }
 await page.getByRole('button',{name:'Scheduled 1 25% — Show trips',exact:true}).click();
 await page.getByLabel('Trip status filter',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('Trip status filter',{exact:true}).inputValue(),'Scheduled');
 assert.equal(await page.locator('.trip-table tbody tr').count(),1);
 await go('Vehicles');
 const register=page.locator('.register-layout'),switcher=register.locator('.register-view-switch');
 await switcher.getByRole('button',{name:'Card view',exact:true}).click();
 await register.locator('.register-cards .vehicle-record').first().waitFor();
 assert.equal(await register.locator('.register-table').isVisible(),false);
 assert.equal(await register.locator('.register-cards .vehicle-record').count(),4);
 const card=register.locator('.vehicle-record').filter({hasText:'FM-102'});
 assert.match(await card.locator('.record-service strong').innerText(),/3[\s,]?600/);
 await audit('Atlas vehicle cards');await fit(register);
 await page.screenshot({path:'browser-results/v6-atlas-register.png',fullPage:true});
 await page.reload();await register.locator('.register-cards .vehicle-record').first().waitFor({timeout:90000});
 await page.addScriptTag({path:axePath});
 await switcher.getByRole('button',{name:'Table view',exact:true}).click();
 await register.locator('.register-table').waitFor();
 await switcher.getByRole('button',{name:'Responsive view',exact:true}).click();
 await page.setViewportSize({width:390,height:900});await register.locator('.register-cards').waitFor();
 assert.equal(await register.locator('.register-table').isVisible(),false);
 await audit('Atlas mobile vehicle cards');
 await go('Calendar');
 await page.locator('.calendar-legend').waitFor();
 assert.equal(await page.locator('.calendar-legend .calendar-dot').count(),3);
 assert.equal(await page.locator('.calendar-today').count(),1);
 await fit(page.locator('.calendar-panel'));
 await go('Help & settings');
 await page.getByLabel('Appearance',{exact:true}).selectOption('light');
 await go('Overview');
 await audit('Atlas light overview');await fit(departure);
 await page.setViewportSize({width:390,height:900});
 await audit('Atlas light mobile overview');await page.screenshot({path:'browser-results/v6-atlas-mobile.png',fullPage:true});
 await go('Help & settings');await page.getByLabel('Workspace visual style',{exact:true}).selectOption('classic');
 await go('Overview');assert.equal(await departure.count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: Atlas next departure, linked status filters, register view persistence, responsive calendar, both themes and classic fallback');
}finally{await browser.close();}
