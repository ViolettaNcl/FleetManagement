 await nav.getByRole('button',{name:'Overview',exact:true}).click();
 await page.locator('.guided-start').waitFor();
 for(const width of [320,360,390,480,768,1024,1440]){
   await page.setViewportSize({width,height:844});
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Guided home overflow '+width);
 }
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Mobile More',exact:true}).click();
 assert.equal(await search.evaluate(el=>el===document.activeElement),false,'Opening menu should not summon keyboard');
 await nav.getByRole('button',{name:'Calendar',exact:true}).click();
