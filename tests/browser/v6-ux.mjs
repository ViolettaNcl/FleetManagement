 await audit('Guided home desktop');
 await page.screenshot({path:'browser-results/v6-guided-desktop.png'});
 const search=nav.getByLabel('Find section',{exact:true});
 await search.fill('model drift');await nav.getByRole('button',{name:'Model Drift',exact:true}).click();
 await page.locator('.guided-context').waitFor();
